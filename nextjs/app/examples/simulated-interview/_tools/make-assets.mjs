// Regenerates the two generated modules beside this folder (run from nextjs/: node app/examples/simulated-interview/_tools/make-assets.mjs):
//   1. ../contextFiles.ts — a copy of the week 9 sample context folder (tdm155ai/tdm155ai-week-9/sample-context-repo), Markdown only,
//      so the example is self-contained.
//   2. ../voices.ts + public/examples/simulated-interview/voices/*.m4a — one clip per spoken line of the script, made with macOS `say`,
//      keyed by a hash of the speaker and text, so a line CX edits later simply plays silently until this is run again.
// Needs macOS (say, afconvert, afinfo). Pass --no-voices to only refresh the context copy.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const here = path.dirname(new URL(import.meta.url).pathname);
const example = path.resolve(here, "..");
const nextjs = path.resolve(example, "../../..");
const contextSrc = process.env.CONTEXT_SRC || path.resolve(nextjs, "../../../tdm155ai/tdm155ai-week-9/sample-context-repo");
const scriptPath = path.resolve(nextjs, "../content/examples/simulated-interview-script.md");
const voicesDir = path.resolve(nextjs, "public/examples/simulated-interview/voices");
const VOICES = { ari: "Daniel", jo: "Samantha" };
const FALLBACK_VOICES = ["Daniel", "Samantha", "Karen", "Moira"];

// Must match hashLine() in script.ts.
function hashLine(id, text) {
  let h = 0x811c9dc5;
  const s = `${id}|${text}`;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
  return h.toString(36);
}

// 1. The context folder
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    if (name.startsWith(".")) continue;
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else if (name.endsWith(".md")) files.push({ path: path.relative(contextSrc, full), content: readFileSync(full, "utf8") });
  }
})(contextSrc);
writeFileSync(path.join(example, "contextFiles.ts"),
  `// GENERATED by _tools/make-assets.mjs from tdm155ai/tdm155ai-week-9/sample-context-repo (public; an invented student). Do not edit by hand.\n` +
  `export type ContextFile = { path: string; content: string };\n\n` +
  `export const contextFiles: ContextFile[] = ${JSON.stringify(files, null, 1)};\n`);
console.log(`context: ${files.length} files`);

if (process.argv.includes("--no-voices")) process.exit(0);

// 2. Voices
const { data, content } = matter(readFileSync(scriptPath, "utf8"));
const humans = (data.speakers || []).filter((s) => s.id !== "producer-ai").map((s) => s.id);
const lines = [];
for (const raw of content.split("\n")) {
  const m = raw.trim().match(/^\*\*([\w-]+)\*\*\s*\[(\d+):(\d{2})\]\s*(.+)$/);
  if (m) lines.push({ id: m[1], start: Number(m[2]) * 60 + Number(m[3]), text: m[4].trim() });
}
lines.sort((a, b) => a.start - b.start);
const spoken = lines.filter((l) => l.id !== "producer-ai");
rmSync(voicesDir, { recursive: true, force: true });
mkdirSync(voicesDir, { recursive: true });
const tmp = path.join(voicesDir, "_tmp.aiff");
const out = {};
spoken.forEach((line, i) => {
  const next = spoken[i + 1]?.start ?? (Number(data.duration) || line.start + 15);
  const room = next - line.start - 0.5;
  const voice = VOICES[line.id] || FALLBACK_VOICES[humans.indexOf(line.id) % FALLBACK_VOICES.length];
  const say = line.text.replace(/\*/g, "").replace(/—/g, ", ");
  const key = hashLine(line.id, line.text);
  const file = path.join(voicesDir, `${key}.m4a`);
  let duration = 0;
  for (let rate = 180; rate <= 280; rate += 15) {
    execFileSync("say", ["-v", voice, "-r", String(rate), "-o", tmp, say]);
    execFileSync("afconvert", ["-f", "m4af", "-d", "aac", "-b", "40000", "-c", "1", tmp, file]);
    duration = Number(execFileSync("afinfo", [file]).toString().match(/estimated duration:\s*([\d.]+)/)?.[1] || 0);
    if (duration <= room) break;
  }
  out[key] = { src: `/examples/simulated-interview/voices/${key}.m4a`, duration: Math.round(duration * 100) / 100 };
  console.log(`${line.id} ${line.start}s ${duration.toFixed(2)}s / room ${room.toFixed(1)}s`);
});
rmSync(tmp, { force: true });
writeFileSync(path.join(example, "voices.ts"),
  `// GENERATED by _tools/make-assets.mjs: one macOS \`say\` clip per spoken line, keyed by hashLine(id, text) in script.ts.\n` +
  `// Voices: ${Object.entries(VOICES).map(([k, v]) => `${k} = ${v}`).join(", ")}. A line whose text has changed since has no clip and plays silently.\n` +
  `export const voices: Record<string, { src: string; duration: number }> = ${JSON.stringify(out, null, 1)};\n`);
